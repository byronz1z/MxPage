  assetId = asset.id;
  const section = await db.pageSection.create({ data: { projectId: "original", sectionKey: "first", type: "CUSTOM", title: "Translated", copy: "", goal: "", visualPrompt: "", order: 0, currentImageAssetId: assetId, editableData: { translationSourceAssetId: assetId } } });
  sectionId = section.id;
  await db.sectionVersion.create({ data: { sectionId, versionNumber: 1, imageAssetId: assetId, promptSnapshot: {}, copySnapshot: {}, isActive: true } });
