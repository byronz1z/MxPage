  db = (await import("../lib/db/prisma")).prisma;
  backups = await import("../lib/storage/data-backups"); recycle = await import("../lib/services/recycle-bin"); projects = await import("../lib/services/project-service");
  await db.project.create({ data: { id: "kept", name: "Existing", platform: "general_ecommerce", style: "generic_clean" } });
  await db.project.create({ data: { id: "original", name: "Original", platform: "general_ecommerce", style: "generic_clean", modelSnapshot: { workType: "translation" } } });
  const storage = await import("../lib/storage/asset-manager");
