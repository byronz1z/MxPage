after(async () => { await db?.$disconnect(); if (root && path.dirname(root) === path.resolve(tmpdir()) && path.basename(root).startsWith("mxpage-data-test-")) await fs.rm(root, { recursive: true, force: true }); });

test("recycle bin hides both lists but preserves original comparison and versions, and restores idempotently", async () => {
  const before = await projects.getProjectDetail("original");
  await projects.deleteProject("original"); await projects.deleteProject("original");
  assert.equal(await projects.getProjectDetail("original"), null);
  assert.equal((await projects.listProjects()).some(project => project.id === "original"), false);
  const history = await import("../lib/services/project-history-service");
  assert.equal((await history.listProjectHistory()).total, 1);
  assert.equal((await recycle.listTrash()).length, 1);
  const lock = await import("../lib/detail-runs/lock");
  await assert.rejects(lock.assertNoDetailRun("original"), /回收站/);
  await recycle.restoreTrash("original"); await recycle.restoreTrash("original");
  const result = await projects.getProjectDetail("original");
  assert.deepEqual(result?.sections, before?.sections);
  assert.deepEqual(result?.assets, before?.assets);
  assert.equal((await history.listProjectHistory()).total, 2);
});
test("recycling refuses pending direct and parent batch work", async () => {
  await db.generationTask.create({ data: { id: "queued", projectId: "original", taskType: "TRANSLATE_PAGE", status: "PENDING" } });
  await assert.rejects(recycle.trashProject("original"), /任务/);
  await db.generationTask.delete({ where: { id: "queued" } });
  await db.generationTask.create({ data: { id: "batch", projectId: "kept", taskType: "BATCH_CREATE", status: "RUNNING", inputPayload: { projectIds: ["original"] } } });
  await assert.rejects(recycle.trashProject("original"), /任务/);
  await db.generationTask.delete({ where: { id: "batch" } });
});
test("backup restores missing projects, source bytes, section links and versions without replacing current edits", async () => {
  const snapshot = await backups.createDataBackup();
  assert.equal(snapshot.files.length, 1);
  const asset = await db.productAsset.findUniqueOrThrow({ where: { id: assetId } });
  await db.project.delete({ where: { id: "original" } });
  await fs.rm(path.join(process.env.STORAGE_ROOT!, asset.filePath));
  await db.project.update({ where: { id: "kept" }, data: { name: "New edits must stay" } });
  const preview = await backups.previewDataRestore(snapshot.id);
  assert.deepEqual(preview.missing.map(project => project.id), ["original"]);
  assert.equal(preview.preserved, 1);
  const restored = await backups.restoreDataBackup(snapshot.id);
  assert.equal(restored.restored, 1);
  assert.equal((await db.project.findUniqueOrThrow({ where: { id: "kept" } })).name, "New edits must stay");
  assert.equal((await fs.readFile(path.join(process.env.STORAGE_ROOT!, asset.filePath))).toString(), "original bytes");
  const result = await projects.getProjectDetail("original");
  assert.equal(result?.sections[0].currentImageAssetId, assetId);
  assert.equal((result?.sections[0].editableData as any).translationSourceAssetId, assetId);
  assert.equal(result?.sections[0].versions[0].imageAssetId, assetId);
  assert.equal((await backups.restoreDataBackup(snapshot.id)).restored, 0);
});
test("corrupted backup is rejected before touching current data", async () => {
  const snapshot = await backups.createDataBackup();
  const before = await db.project.findMany();
  const file = path.join(backups.dataPaths().backups, snapshot.id, "files", snapshot.files[0].path);
  await fs.writeFile(file, "corrupted");
  await assert.rejects(backups.previewDataRestore(snapshot.id), /校验失败/);
  await assert.rejects(backups.restoreDataBackup(snapshot.id), /校验失败/);
  assert.deepEqual(await db.project.findMany(), before);
  await assert.rejects(backups.previewDataRestore("../../outside"), /标识无效/);
});
test("restore rejects file conflicts and rolls back added database records", async () => {
  const snapshot = await backups.createDataBackup();
  const asset = await db.productAsset.findUniqueOrThrow({ where: { id: assetId } });
  await db.project.delete({ where: { id: "original" } });
  const file = path.join(process.env.STORAGE_ROOT!, asset.filePath);
  await fs.writeFile(file, "new unrelated contents");
  await assert.rejects(backups.restoreDataBackup(snapshot.id), /文件冲突/);
  assert.equal(await db.project.findUnique({ where: { id: "original" } }), null);
  assert.equal(await fs.readFile(file, "utf8"), "new unrelated contents");
  await fs.rm(file);
  await backups.restoreDataBackup(snapshot.id);
});
test("unfinished tasks are restored for manual recovery and never restarted automatically", async () => {
  await db.project.create({ data: { id: "unfinished", name: "Unfinished", platform: "general_ecommerce", style: "generic_clean" } });
  await db.generationTask.create({ data: { id: "unfinished-task", projectId: "unfinished", taskType: "TRANSLATE_PAGE", status: "RUNNING", inputPayload: { requestId: "preserve-uncertain-request" } } });
  const snapshot = await backups.createDataBackup();
  await assert.rejects(backups.restoreDataBackup(snapshot.id), /停止运行/);
  await db.project.delete({ where: { id: "unfinished" } });
  await backups.restoreDataBackup(snapshot.id);
  const task = await db.generationTask.findUniqueOrThrow({ where: { id: "unfinished-task" } });
  assert.equal(task.status, "FAILED");
  assert.deepEqual(task.inputPayload, { requestId: "preserve-uncertain-request" });
});
test("missing source files prevent incomplete snapshots from appearing as valid backups", async () => {
  const before = (await backups.dataOverview()).backups.length;
  const asset = await db.productAsset.findUniqueOrThrow({ where: { id: assetId } });
  const file = path.join(process.env.STORAGE_ROOT!, asset.filePath);
  const bytes = await fs.readFile(file);
  await fs.rm(file);
  try { await assert.rejects(backups.createDataBackup(), /ENOENT/); assert.equal((await backups.dataOverview()).backups.length, before); }
  finally { await fs.writeFile(file, bytes); }
});
test("upload routes reject bad bytes without writing records and budget checks preserve idempotent retries", async () => {
  const { NextRequest } = await import("next/server");
  const { POST } = await import("../app/api/projects/[id]/assets/upload/route");
  const upload = (body: unknown) => POST(new NextRequest("http://local/api/upload", { method: "POST", body: JSON.stringify(body) }), { params: { id: "kept" } });
  const body = { type: "MAIN", fileName: "valid.png", mimeType: "image/png", base64Data: Buffer.from("invalid").toString("base64"), uploadKey: "stable-upload" };
  assert.equal((await upload(body)).status, 400);
  assert.equal(await db.productAsset.count({ where: { projectId: "kept" } }), 0);
  const sharp = (await import("sharp")).default;
  body.base64Data = (await sharp({ create: { width: 2, height: 2, channels: 3, background: "white" } }).png().toBuffer()).toString("base64");
  const accepted = await (await upload(body)).json();
  assert.equal(accepted.success, true);
  const asset = await db.productAsset.findUniqueOrThrow({ where: { id: accepted.data.id } });
  await db.productAsset.update({ where: { id: asset.id }, data: { metadata: { ...(asset.metadata as object), bytes: 300 * 1024 * 1024 } } });
  assert.equal((await (await upload(body)).json()).data.id, asset.id);
  assert.equal((await (await upload({ ...body, uploadKey: "new-upload" })).json()).success, false);
  assert.equal(await db.productAsset.count({ where: { projectId: "kept" } }), 1);
  const legacy = await import("../app/api/tasks/batch-create/route");
  const before = await db.project.count();
  const invalidBatch = await legacy.POST(new NextRequest("http://local/api/tasks/batch-create", { method: "POST", body: JSON.stringify({ files: [{ fileName: "bad.png", mimeType: "image/png", base64Data: "bm90LWltYWdl" }] }) }));
  assert.equal((await invalidBatch.json()).success, false);
  assert.equal(await db.project.count(), before);
});
