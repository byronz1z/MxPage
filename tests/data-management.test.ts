  const sqlite = new DatabaseSync(path.join(root, "test.db"));
  for (const folder of (await fs.readdir("prisma/migrations", { withFileTypes: true })).filter(item => item.isDirectory()).sort((a,b) => a.name.localeCompare(b.name))) sqlite.exec(await fs.readFile(path.join("prisma/migrations", folder.name, "migration.sql"), "utf8"));
